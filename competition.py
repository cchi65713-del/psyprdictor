"""
Competition Engine for PsyPredictor.

This module introduces the new behavioral-tendency competition model.

Flow:
    BehavioralTendency
        ↓
    Normalization
        ↓
    Weighted competition
        ↓
    Conflict detection
        ↓
    CompetitionResult

This module does NOT replace arbitration.py yet.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional


# ============================================================
# 1. BEHAVIORAL TENDENCY
# ============================================================

@dataclass
class BehavioralTendency:
    """
    A behavioral pressure generated by one PsyPredictor subsystem.

    Each subsystem can independently say:
        "I am pushing toward this action."
    """

    action: str

    # Original signal from the subsystem.
    raw_strength: float

    # Canonical 0-1 representation.
    normalized_strength: float = 0.0

    # Source subsystem.
    # Examples:
    #   goal_directed
    #   habitual
    #   reactive
    source: str = ""

    # Evidence supporting the tendency.
    supporting_evidence: List[str] = field(default_factory=list)

    # Human-readable explanation.
    reason: str = ""

    # Confidence of the subsystem's own proposal.
    confidence_in_proposal: float = 1.0

    # Extra context that may become useful later.
    context_tags: Dict = field(default_factory=dict)

    # Information about normalization.
    normalization_factor: float = 1.0
    raw_before_norm: Optional[float] = None

    # Adjusted strength after SystemMemory influence (0-1).
    adjusted_strength: float = 0.0

    # Multiplicative factor returned by SystemMemory (1.0 == neutral)
    system_memory_factor: float = 1.0

    # Human-readable reasons provided by SystemMemory
    system_memory_reasons: List[str] = field(default_factory=list)

    def __post_init__(self):
        # Preserve original raw value.
        if self.raw_before_norm is None:
            self.raw_before_norm = self.raw_strength

        # Keep confidence within 0-1.
        self.confidence_in_proposal = max(
            0.0,
            min(1.0, self.confidence_in_proposal)
        )


# ============================================================
# 2. COMPETITION RESULT
# ============================================================

@dataclass
class CompetitionResult:
    """
    Complete result of the internal behavioral competition.
    """

    selected_action: Optional[str]

    selected_source: str = ""

    final_strength: float = 0.0

    decision_confidence: float = 0.0


    conflict_level: str = "none"

    # New explicit fields requested
    conflict_type: str = ""

    conflict_sources: List[str] = field(default_factory=list)

    winning_action: Optional[str] = None
    runner_up_action: Optional[str] = None
    winning_pressure: float = 0.0
    runner_up_pressure: float = 0.0
    margin_of_victory: float = 0.0
    # Backwards-compatible field name used by older tests/scripts
    conflict_margin: float = 0.0
    margin_percentage: float = 0.0

    all_proposals: List[BehavioralTendency] = field(
        default_factory=list
    )

    action_pressures: Dict[str, float] = field(
        default_factory=dict
    )

    reasoning: str = ""

    system_memory_influence: Dict = field(
        default_factory=dict
    )

    # Structured conflict information
    conflict_info: Dict = field(default_factory=dict)
    # Confidence components for transparency
    margin_score: float = 0.0
    convergence_score: float = 0.0
    source_confidence_score: float = 0.0
    evidence_score: float = 0.0
    confidence_breakdown: Dict = field(default_factory=dict)


# ============================================================
# 3. COMPETITION CONFIGURATION
# ============================================================

DEFAULT_SUBSYSTEM_WEIGHTS = {
    "goal_directed": 1.0,
    "habitual": 1.0,
    "reactive": 1.0,
}


# ============================================================
# 4. NORMALIZATION
# ============================================================

def normalize_tendency(
    tendency: BehavioralTendency
) -> BehavioralTendency:
    """
    Convert a subsystem's raw strength to a 0-1 scale.

    Current assumptions:

        goal_directed -> 0-100
        reactive      -> 0-100
        habitual      -> 0-10

    These scales are explicit and can be changed later.
    """

    raw = max(0.0, tendency.raw_strength)

    if tendency.source in ("goal_directed", "reactive"):
        normalized = min(raw / 100.0, 1.0)
        factor = 1.0 / 100.0

    elif tendency.source in ("habit", "habitual"):
        normalized = min(raw / 10.0, 1.0)
        factor = 1.0 / 10.0

    else:
        # Unknown source:
        # assume the supplied value is already 0-1.
        normalized = min(raw, 1.0)
        factor = 1.0

    tendency.normalized_strength = normalized
    tendency.normalization_factor = factor

    # Initialize adjusted strength to normalized by default.
    tendency.adjusted_strength = tendency.normalized_strength

    return tendency


def normalize_tendencies(
    tendencies: List[BehavioralTendency]
) -> List[BehavioralTendency]:
    """
    Normalize all tendencies.
    """

    return [
        normalize_tendency(tendency)
        for tendency in tendencies
    ]


# ============================================================
# 5. COMPETITION ENGINE
# ============================================================

class CompetitionEngine:
    """
    Resolves competing behavioral tendencies.
    """

    def __init__(
        self,
        subsystem_weights: Optional[Dict[str, float]] = None,
        system_memory=None
    ):
        self.subsystem_weights = (
            subsystem_weights.copy()
            if subsystem_weights
            else DEFAULT_SUBSYSTEM_WEIGHTS.copy()
        )
        # Optional SystemMemory instance; set via constructor if available.
        self.system_memory = system_memory

    def compete(
        self,
        tendencies: List[BehavioralTendency],
        person: Optional[str] = None
    ) -> CompetitionResult:
        """
        Run the complete competition process.
        """

        if not tendencies:
            return CompetitionResult(
                selected_action=None,
                reasoning="No behavioral tendencies were provided."
            )

        # ----------------------------------------------------
        # STEP 1: NORMALIZATION
        # ----------------------------------------------------

        tendencies = normalize_tendencies(tendencies)

        # ----------------------------------------------------
        # STEP 2: CALCULATE INDIVIDUAL PRESSURES
        # ----------------------------------------------------

        individual_pressures = []

        # If a SystemMemory instance is available on this engine, use it to
        # compute a multiplicative factor per tendency. The factor is applied
        # to the tendency's normalized strength to produce `adjusted_strength`.
        for tendency in tendencies:

            # Ask SystemMemory for an adjustment factor (if present). Keep
            # default neutral factor 1.0 when no memory is available.
            if self.system_memory is not None:
                try:
                    factor, reasons = self.system_memory.assess_tendency(
                        person,
                        tendency
                    )
                except Exception:
                    factor, reasons = 1.0, []
            else:
                factor, reasons = 1.0, []

            tendency.system_memory_factor = factor
            tendency.system_memory_reasons = reasons

            # Apply factor to normalized strength (preserve transparency).
            tendency.adjusted_strength = (
                tendency.normalized_strength * factor
            )

            weight = self.subsystem_weights.get(
                tendency.source,
                1.0
            )

            pressure = (
                tendency.adjusted_strength
                * weight
                * tendency.confidence_in_proposal
            )

            individual_pressures.append(
                (tendency, pressure)
            )

        # ----------------------------------------------------
        # STEP 3: GROUP PRESSURE BY ACTION
        # ----------------------------------------------------

        action_pressures: Dict[str, float] = {}

        for tendency, pressure in individual_pressures:

            if tendency.action not in action_pressures:
                action_pressures[tendency.action] = 0.0

            action_pressures[tendency.action] += pressure

        # ----------------------------------------------------
        # STEP 4: FIND WINNER
        # ----------------------------------------------------

        ranked_actions = sorted(
            action_pressures.items(),
            key=lambda item: item[1],
            reverse=True
        )

        winning_action = ranked_actions[0][0]
        winning_pressure = ranked_actions[0][1]

        if len(ranked_actions) > 1:
            runner_up_action = ranked_actions[1][0]
            runner_up_pressure = ranked_actions[1][1]
        else:
            runner_up_action = None
            runner_up_pressure = 0.0

        # ----------------------------------------------------
        # STEP 5: MARGIN
        # ----------------------------------------------------

        margin = (
            winning_pressure - runner_up_pressure
        )

        if winning_pressure > 0:
            margin_percentage = (
                margin / winning_pressure
            )
        else:
            margin_percentage = 0.0

        # ----------------------------------------------------
        # STEP 6: DETECT CONFLICT
        # ----------------------------------------------------

        unique_actions = set(
            tendency.action
            for tendency in tendencies
        )

        # Determine conflict level (human-friendly)
        if len(unique_actions) == 1:
            conflict_level = "none"
        elif margin_percentage < 0.10:
            conflict_level = "high"
        elif margin_percentage < 0.50:
            conflict_level = "moderate"
        else:
            conflict_level = "mild"

        # Determine conflict type using pressures and coalition patterns.
        # Do not classify based only on number of systems; use actual pressures.
        if len(unique_actions) == 1:
            conflict_type = "unanimous"
            conflict_exists = False
        else:
            conflict_exists = True

            # Close competition when top two pressures are nearly equal.
            if margin_percentage < 0.05:
                conflict_type = "close_competition"

            else:
                # Count distinct sources supporting winner and runner-up
                winner_sources = [
                    t.source for t in tendencies if t.action == winning_action
                ]

                runner_sources = [
                    t.source for t in tendencies if t.action == runner_up_action
                ]

                if len(set(winner_sources)) > len(set(runner_sources)) and len(set(winner_sources)) >= 2:
                    conflict_type = "coalition_override"
                else:
                    conflict_type = "direct_opposition"

        # ----------------------------------------------------
        # STEP 7: FIND SOURCES INVOLVED
        # ----------------------------------------------------

        conflict_sources = list(
            dict.fromkeys(
                tendency.source
                for tendency in tendencies
                if tendency.action != winning_action
            )
        )

        winning_sources = list(
            dict.fromkeys(
                tendency.source
                for tendency in tendencies
                if tendency.action == winning_action
            )
        )

        # Build proposals_by_source: mapping source -> list of proposal summaries
        proposals_by_source = {}
        for tendency, pressure in individual_pressures:
            proposals_by_source.setdefault(tendency.source, []).append({
                "action": tendency.action,
                "raw": tendency.raw_strength,
                "normalized": tendency.normalized_strength,
                "adjusted": tendency.adjusted_strength,
                "pressure": pressure,
            })

        # ----------------------------------------------------
        # STEP 8: BUILD REASONING
        # ----------------------------------------------------

        reasoning_parts = []

        if len(unique_actions) == 1:

            reasoning_parts.append(
                f"All behavioral systems proposed "
                f"{winning_action}."
            )

        else:

            reasoning_parts.append(
                "Internal behavioral conflict detected."
            )

            reasoning_parts.append(
                f"Winning action: {winning_action} "
                f"with pressure {winning_pressure:.4f}."
            )

            if runner_up_action is not None:
                reasoning_parts.append(
                    f"Runner-up: {runner_up_action} "
                    f"with pressure {runner_up_pressure:.4f}."
                )

            reasoning_parts.append(
                f"Margin: {margin_percentage:.2%}."
            )

            reasoning_parts.append(
                f"Winning sources: "
                f"{', '.join(winning_sources)}."
            )

            if conflict_sources:
                reasoning_parts.append(
                    f"Opposing sources: "
                    f"{', '.join(conflict_sources)}."
                )

        # Build human-readable reason lists for conflict_info
        why_winner_won = []
        why_runner_up_lost = []

        for src in winning_sources:
            parts = proposals_by_source.get(src, [])
            for p in parts:
                if p["action"] == winning_action:
                    why_winner_won.append(
                        f"{src} proposed {p['action']} with pressure {p['pressure']:.4f}"
                    )

        for src in conflict_sources:
            parts = proposals_by_source.get(src, [])
            for p in parts:
                if p["action"] == runner_up_action:
                    why_runner_up_lost.append(
                        f"{src} proposed {p['action']} with pressure {p['pressure']:.4f}"
                    )

        # ----------------------------------------------------
        # STEP 9: INITIAL CONFIDENCE
        # ----------------------------------------------------

        margin_score = min(
            margin_percentage / 0.50,
            1.0
        )

        total_sources = len(tendencies)

        agreeing_sources = sum(
            1
            for tendency in tendencies
            if tendency.action == winning_action
        )

        convergence_score = (
            agreeing_sources / total_sources
            if total_sources
            else 0.0
        )

        # A single winning source, or a single action with no real opposition,
        # should not be treated as near-certain. This is the main calibration
        # issue behind one B1 experience creating excessive RespondImmediately
        # confidence in the competition layer.
        if len(unique_actions) == 1 and total_sources <= 2:
            margin_score = min(margin_score, 0.50)
            convergence_score = min(convergence_score, 0.60)

        # Source confidence should reflect only the subsystems that
        # supported the winning action.
        supporting_tendencies = [
            t for t in tendencies if t.action == winning_action
        ]

        source_confidence_score = (
            sum(t.confidence_in_proposal for t in supporting_tendencies) /
            len(supporting_tendencies)
            if supporting_tendencies
            else 0.0
        )

        # A single habit/memory signal with only one piece of evidence should not
        # count as highly certain support.
        if len(supporting_tendencies) == 1 and len(supporting_tendencies[0].supporting_evidence) <= 1:
            source_confidence_score *= 0.75

        evidence_count = sum(
            len(tendency.supporting_evidence)
            for tendency in tendencies
            if tendency.action == winning_action
        )

        evidence_score = min(
            evidence_count / 3.0,
            1.0
        )

        decision_confidence = (
            0.40 * margin_score
            + 0.30 * convergence_score
            + 0.20 * source_confidence_score
            + 0.10 * evidence_score
        )

        decision_confidence = max(
            0.0,
            min(1.0, decision_confidence)
        )

        # Build confidence breakdown for transparency
        confidence_breakdown = {
            "margin_score": margin_score,
            "convergence_score": convergence_score,
            "source_confidence_score": source_confidence_score,
            "evidence_score": evidence_score,
            "weights": {
                "margin": 0.40,
                "convergence": 0.30,
                "source_confidence": 0.20,
                "evidence": 0.10,
            }
        }

        # ----------------------------------------------------
        # STEP 10: RETURN COMPLETE RESULT
        # ----------------------------------------------------

        conflict_info = {
            "exists": conflict_exists,
            "type": conflict_type,
            "level": conflict_level,
            "winning_action": winning_action,
            "runner_up_action": runner_up_action,
            "winning_pressure": winning_pressure,
            "runner_up_pressure": runner_up_pressure,
            "margin_of_victory": margin,
            "margin_percentage": margin_percentage,
            "proposals_by_source": proposals_by_source,
            "reasons": {
                "why_winner_won": why_winner_won,
                "why_runner_up_lost": why_runner_up_lost,
                "conflict_resolution": "",
            },
        }

        return CompetitionResult(
            selected_action=winning_action,
            selected_source="+".join(winning_sources),
            final_strength=winning_pressure,
            decision_confidence=decision_confidence,
            conflict_level=conflict_level,
            conflict_type=conflict_type,
            conflict_sources=conflict_sources,
            winning_action=winning_action,
            runner_up_action=runner_up_action,
            winning_pressure=winning_pressure,
            runner_up_pressure=runner_up_pressure,
            margin_of_victory=margin,
            conflict_margin=margin,
            margin_percentage=margin_percentage,
            margin_score=margin_score,
            convergence_score=convergence_score,
            source_confidence_score=source_confidence_score,
            evidence_score=evidence_score,
            confidence_breakdown=confidence_breakdown,
            all_proposals=tendencies,
            action_pressures=action_pressures,
            system_memory_influence={},
            reasoning=" ".join(reasoning_parts),
            conflict_info=conflict_info,
        )